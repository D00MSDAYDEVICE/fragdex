"""Generate app/scanner-win/HuffmanTable.cs from fragdex/importers/huffman_table.py.

The Windows scanner is C#, so it carries its own copy of the Huffman codes;
tests/test_importers.py checks the two never drift apart.
    python tools/gen_huffman_cs.py
"""
import os
import sys

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, APP)

from fragdex.importers.huffman_table import CODES  # noqa: E402

OUT = os.path.join(APP, "scanner-win", "HuffmanTable.cs")


def render():
    codes = [CODES[i] for i in range(len(CODES))]
    rows = []
    for i in range(0, len(codes), 8):
        rows.append("            " + " ".join(f'"{c}",' for c in codes[i:i + 8]))
    return (
        "// SPDX-License-Identifier: GPL-2.0-or-later\n"
        "// Generated by app/tools/gen_huffman_cs.py - do not edit.\n"
        "// Bit strings in stream order (first char = first bit read) for each byte value\n"
        "// (index 256 = NYT) of the Quake 3 / Quake Live message Huffman tree (ioquake3, GPLv2).\n"
        "namespace Fragdex\n{\n"
        "    static class HuffmanTable\n    {\n"
        "        public static readonly string[] Codes = {\n"
        + "\n".join(rows) + "\n"
        "        };\n    }\n}\n"
    )


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(render())
    print(f"wrote {OUT}")
