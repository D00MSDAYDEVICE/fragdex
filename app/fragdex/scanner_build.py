"""Build the standalone fragdex-scan.py from the app's own parser modules.

The scanner shares its parsing code with the server, so the download can never
drift out of sync with what the server imports. Usage:
    python -m fragdex.scanner_build [OUTPUT]      (default: fragdex-scan.py)
"""
import os
import re
import sys
from functools import lru_cache

from . import __version__

HERE = os.path.dirname(__file__)
MODULES = (
    "importers/common.py",
    "importers/huffman_table.py",
    "importers/demo.py",
    "importers/logs.py",
    "importers/export.py",
    "scanner.py",
)
RELATIVE_IMPORT_RE = re.compile(r"^from \.[\w.]* import (?:\([^)]*\)|[^\n]*)\n", re.M)

HEADER = '''#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0-or-later
# fragdex-scan {version} - standalone build, generated by Fragdex. Needs Python 3.8+ only
# (no packages). Quake 3 Huffman table from ioquake3 (GPLv2). This program is free
# software under the GNU General Public License v2 or later, without any warranty.
#
#   python fragdex-scan.py                    scan the default demo folders
#   python fragdex-scan.py "D:\\\\QL\\\\demos"     scan a folder
#   python fragdex-scan.py --help
__version__ = "{version}"
'''


@lru_cache(maxsize=1)
def build_script() -> str:
    parts = [HEADER.format(version=__version__)]
    for rel in MODULES:
        with open(os.path.join(HERE, *rel.split("/")), encoding="utf-8") as f:
            src = RELATIVE_IMPORT_RE.sub("", f.read())
        parts.append(f"\n# {'-' * 70}\n# {rel}\n# {'-' * 70}\n{src}")
    return "".join(parts)


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "fragdex-scan.py"
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(build_script())
    print(f"wrote {out}")
